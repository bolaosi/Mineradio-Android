/* Deterministic, dependency-free bundler for the installed MIT node-qrcode browser entry. */
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');

const root = path.resolve(__dirname, '..');
const backend = path.join(root, 'app/src/main/assets/nodejs-project');
const packages = ['qrcode', 'dijkstrajs'].map(name => {
  const manifest = require.resolve(name + '/package.json', { paths: [backend] });
  return { name, directory: path.dirname(manifest), ...JSON.parse(fs.readFileSync(manifest, 'utf8')) };
});
const versions = { qrcode: '1.5.4', dijkstrajs: '1.0.3' };
for (const pkg of packages) {
  if (pkg.version !== versions[pkg.name]) throw new Error('Review the new upstream source before bundling ' + pkg.name + '@' + pkg.version);
}
const ids = new Map(), modules = [];
function include(file) {
  if (!packages.some(pkg => file.startsWith(pkg.directory + path.sep))) throw new Error('Unexpected browser dependency: ' + file);
  if (ids.has(file)) return ids.get(file);
  const id = modules.length;
  ids.set(file, id); modules.push(null);
  let source = fs.readFileSync(file, 'utf8').replace(/\r\n/g, '\n');
  source = source.replace(/\brequire\s*\(\s*(['"])([^'"]+)\1\s*\)/g, (_, quote, request) => {
    const dependency = require.resolve(request, { paths: [path.dirname(file)] });
    return '__load(' + include(dependency) + ')';
  });
  if (/\brequire\s*\(/.test(source)) throw new Error('A non-static CommonJS import needs review: ' + file);
  const label = path.relative(path.join(backend, 'node_modules'), file).replace(/\\/g, '/');
  modules[id] = '// ' + label + '\nfunction(module, exports, __load) {\n' + source + '\n}';
  return id;
}
const entry = include(require.resolve('qrcode/lib/browser.js', { paths: [backend] }));
const licenses = packages.map(pkg => {
  const license = path.join(pkg.directory, pkg.name === 'qrcode' ? 'license' : 'LICENSE.md');
  return pkg.name + '@' + pkg.version + '\n' + fs.readFileSync(license, 'utf8').replace(/\r\n/g, '\n');
}).join('\n\n');
const bundle = '/* Generated by scripts/build-android-qrcode.cjs. Do not edit this bundle.\n' +
  'Offline browser QR encoder; includes the complete upstream licenses below.\n\n' + licenses.replace(/\*\//g, '* /') + '\n*/\n' +
  '(function(root) {\n\'use strict\';\nvar factories = [\n' + modules.join(',\n') + '\n];\n' +
  'var cache = Object.create(null);\nfunction __load(id) {\n' +
  '  if (cache[id]) return cache[id].exports;\n  var module = cache[id] = { exports: {} };\n' +
  '  factories[id](module, module.exports, __load);\n  return module.exports;\n}\n' +
  'var encoder = __load(' + entry + ');\n' +
  'root.MineradioQr = Object.freeze({ toDataURL: function(text) {\n' +
  '  return Promise.resolve().then(function() {\n' +
  '    if (typeof text !== \'string\' || !text.trim() || text.length > 2048) throw new Error(\'二维码内容无效或过长\');\n' +
  '    return encoder.toDataURL(text, { type: \'image/png\', errorCorrectionLevel: \'M\', margin: 4, scale: 8, color: { dark: \'#000000\', light: \'#ffffff\' } });\n' +
  '  });\n} });\n})(window);\n';
const target = path.join(root, 'app/src/main/assets/android-qrcode.js');
fs.writeFileSync(target, bundle, 'utf8');
console.log(JSON.stringify({ target: path.relative(root, target).replace(/\\/g, '/'), modules: modules.length, bytes: Buffer.byteLength(bundle), sha256: crypto.createHash('sha256').update(bundle).digest('hex') }));
