/* Strict simulated native bridge + real bundled browser UI. NOT Android or real-account authentication. */
const assert = require('node:assert/strict');
const http = require('node:http');
const fs = require('node:fs');
const path = require('node:path');
const os = require('node:os');
const { execFileSync } = require('node:child_process');
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');

function installMockBridge(options) {
  const verified = { provider: 'netease', loggedIn: true, verified: true, saved: true, userId: '900001', nickname: 'MOCK 模拟账号', vipType: 0 };
  const state = window.__nativeMock = { mode: 'pending', account: null, serial: 0, requests: [], checks: {}, configReplies: [], held: [], holdConfig: options.holdConfig, savedImages: [], statusCalls: 0, playlistCalls: 0 };
  function emit(id, result, error) {
    setTimeout(() => window.MineradioNative.onmessage({ data: JSON.stringify({ id, result, error: error || null }) }), 0);
  }
  state.releaseConfig = function () { state.holdConfig = false; state.configReplies.splice(0).forEach(id => emit(id, { mode: 'builtin', ready: true })); };
  state.releaseHeld = function () { state.held.splice(0).forEach(id => emit(id, { status: 200, body: JSON.stringify({ code: 803, ...verified }) })); };
  function route(command) {
    const url = new URL(command.path, location.origin), pathname = url.pathname;
    if (!command.path.startsWith('/api/') || command.backend || !['GET', 'POST'].includes(command.method) || typeof command.body !== 'string') throw new Error('Invalid native request contract');
    if (pathname === '/api/login/status') { state.statusCalls++; return state.account || { loggedIn: false, verified: false }; }
    if (pathname === '/api/qq/login/status') return { provider: 'qq', loggedIn: false, verified: false };
    if (pathname === '/api/login/qr/key') {
      const key = 'MOCK_ONLY_BUILTIN_KEY_' + ++state.serial; state.checks[key] = 0; return { key };
    }
    if (pathname === '/api/login/qr/create') {
      state.qrUrl = 'https://music.163.com/login?codekey=' + encodeURIComponent(url.searchParams.get('key'));
      return { url: state.qrUrl }; // The PNG must be generated by the real offline browser encoder.
    }
    if (pathname === '/api/login/qr/check') {
      const key = url.searchParams.get('key'), count = ++state.checks[key];
      if (state.mode === 'late') { state.held.push(command.id); return null; }
      if (state.mode === 'unverified') return { code: 803, saved: true, verified: false, loggedIn: false, message: 'MOCK：凭据待验证，尚未登录' };
      if (state.mode === 'expired') return { code: count === 1 ? 801 : count === 2 ? 802 : 800 };
      if (state.mode === 'success') {
        if (count < 3) return { code: count === 1 ? 801 : 802 };
        state.account = verified; return { code: 803, ...verified };
      }
      return { code: 801 };
    }
    if (pathname === '/api/user/playlists') { state.playlistCalls++; return { playlists: [{ id: 'mock-playlist', name: 'MOCK 验证后歌单', trackCount: 0 }] }; }
    if (pathname === '/api/podcast/my') return { collections: [] };
    if (pathname === '/api/discover/home') return { loggedIn: !!state.account, songs: [], playlists: [], podcasts: [], dailySongs: [] };
    if (pathname === '/api/logout') { state.account = null; return { ok: true }; }
    if (pathname === '/api/qq/login/cookie') return { provider: 'qq', loggedIn: false, verified: false, saved: false, error: 'MOCK_INVALID_COOKIE', message: 'MOCK：QQ Cookie 无效，未保存' };
    return { songs: [], ids: [], playlists: [], collections: [] };
  }
  window.MineradioNative = {
    onmessage: null,
    postMessage(raw) {
      const command = JSON.parse(raw);
      if (!command.id || typeof command.id !== 'string') throw new Error('Native id must be a string');
      state.requests.push({ type: command.type, path: command.path ? new URL(command.path, location.origin).pathname : undefined });
      if (command.type === 'cancel') return;
      if (command.type === 'getConfig') {
        if (state.holdConfig) state.configReplies.push(command.id); else emit(command.id, { mode: 'builtin', ready: true });
        return;
      }
      if (command.type === 'saveConfig') throw new Error('Builtin UI must never save backend credentials');
      if (command.type === 'saveQr') {
        if (!/^data:image\/png;base64,/.test(command.dataUri) || command.dataUri.length < 2000) throw new Error('Real PNG required');
        state.savedImages.push(command.dataUri); emit(command.id, { saved: true }); return;
      }
      if (command.type !== 'request') throw new Error('Unexpected native operation');
      const reply = route(command);
      if (reply) emit(command.id, { status: command.path.startsWith('/api/qq/login/cookie') ? 401 : 200, body: JSON.stringify(reply) });
    }
  };
}

async function main() {
  const root = path.resolve(__dirname, '..'), assets = path.join(root, 'app/src/main/assets');
  const output = path.join(root, 'output/playwright'); fs.mkdirSync(output, { recursive: true });
  const temporary = fs.mkdtempSync(path.join(os.tmpdir(), 'mineradio-builtin-test-'));
  const mp3 = path.join(temporary, 'mock-test-tone.mp3');
  execFileSync('ffmpeg', ['-hide_banner', '-loglevel', 'error', '-f', 'lavfi', '-i', 'sine=frequency=620:duration=20', '-codec:a', 'libmp3lame', mp3]);
  const httpRequests = [], external = [], pageErrors = [], consoleErrors = [], checks = [];
  let browser, passed = false, bridgeRequests = [];
  const server = http.createServer((request, response) => {
    const pathname = new URL(request.url, 'http://localhost').pathname;
    httpRequests.push({ method: request.method, path: pathname });
    const file = path.resolve(assets, '.' + (pathname === '/' ? '/index.html' : pathname));
    if (!file.startsWith(assets + path.sep) || !fs.existsSync(file) || !fs.statSync(file).isFile()) { response.writeHead(404); response.end(); return; }
    response.setHeader('Content-Type', file.endsWith('.html') ? 'text/html; charset=utf-8' : file.endsWith('.js') ? 'application/javascript' : 'application/octet-stream');
    response.end(fs.readFileSync(file));
  });
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
  const origin = 'http://127.0.0.1:' + server.address().port;
  function record(name) { checks.push(name); console.log('PASS ' + name); }
  async function createPage(holdConfig) {
    const page = await browser.newPage({ viewport: { width: 390, height: 844 } });
    page.on('pageerror', error => pageErrors.push(error.message));
    page.on('console', message => { if (message.type() === 'error') consoleErrors.push(message.text()); });
    await page.addInitScript(installMockBridge, { holdConfig });
    await page.route('**/*', route => {
      if (route.request().url().startsWith(origin + '/')) return route.continue();
      external.push(route.request().url()); return route.abort();
    });
    await page.goto(origin);
    await page.waitForFunction(() => !!window.AndroidLocal && !!window.AndroidOnlineSettings);
    return page;
  }
  async function enter(page) {
    if (await page.evaluate(() => document.body.classList.contains('splash-active'))) {
      await page.waitForFunction(() => window.splashReadyToEnter === true);
      await page.locator('#splash').click({ position: { x: 25, y: 60 } });
      await page.waitForFunction(() => !document.body.classList.contains('splash-active'));
    }
    await page.waitForTimeout(300);
    const skip = page.locator('#visual-guide-skip'); if (await skip.count() && await skip.isVisible()) await skip.click();
    const close = page.locator('#login-modal .btn-row button').filter({ hasText: '取消' }); if (await close.isVisible()) await close.click();
  }
  async function closeLogin(page) { await page.locator('#login-modal .btn-row button').filter({ hasText: '取消' }).click(); }
  async function login(page, mode) {
    await page.evaluate(value => { window.__nativeMock.mode = value; }, mode);
    await page.locator('#user-btn').click();
    await page.waitForFunction(() => document.getElementById('login-modal').classList.contains('show'));
    await page.locator('#login-provider-netease').click();
  }
  try {
    const launch = { headless: true, args: ['--autoplay-policy=no-user-gesture-required', '--enable-webgl', '--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader'] };
    if (process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE) launch.executablePath = process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE;
    browser = await chromium.launch(launch);
    const page = await createPage(false); await enter(page);
    assert.deepEqual(await page.evaluate(() => window.AndroidRuntime.getConfig()), { mode: 'builtin', ready: true });
    await page.locator('#android-online-button').click();
    assert.match(await page.locator('#android-online-settings').innerText(), /无需后端地址、令牌或电脑/);
    assert.equal(await page.locator('#android-online-settings input').count(), 0);
    assert.equal(await page.locator('#online-base, #online-token').count(), 0);
    await page.locator('#online-close').click();
    record('first native launch uses builtin mode without any address or token input');

    await login(page, 'expired');
    await page.waitForFunction(() => document.getElementById('qr-img').naturalWidth >= 200);
    const qr = await page.evaluate(() => ({ image: document.getElementById('qr-img').src, text: window.__nativeMock.qrUrl }));
    const qrPath = path.join(output, 'android-builtin-fake-key-qr.png');
    fs.writeFileSync(qrPath, Buffer.from(qr.image.slice(qr.image.indexOf(',') + 1), 'base64'));
    const manifest = path.join(output, 'android-builtin-fake-key-qr-manifest.json');
    fs.writeFileSync(manifest, JSON.stringify([{ path: qrPath, text: qr.text }]));
    const decoded = JSON.parse(execFileSync(process.env.PYTHON || 'python', ['-X', 'utf8', path.join(__dirname, 'decode-android-qrcode.py'), manifest], { encoding: 'utf8' }));
    assert.equal(decoded.passed, true);
    await page.locator('#android-save-qr').click();
    assert.equal(await page.evaluate(() => window.__nativeMock.savedImages.length), 1);
    await page.screenshot({ path: path.join(output, 'android-builtin-mock-qr.png') });
    record('official-format fake key URL becomes a real locally generated, independently decoded PNG and reaches save RPC');
    await page.waitForFunction(() => /已扫码/.test(document.getElementById('qr-status').textContent), null, { timeout: 12000 });
    await page.waitForFunction(() => /过期/.test(document.getElementById('qr-status').textContent), null, { timeout: 12000 });
    assert.equal(await page.locator('#qr-shell').isVisible(), false);
    const previousKey = await page.evaluate(() => window.__nativeMock.serial);
    await page.evaluate(() => { window.__nativeMock.mode = 'pending'; });
    await page.locator('#refresh-qr-btn').click();
    await page.waitForFunction(previous => window.__nativeMock.serial > previous && document.getElementById('qr-img').naturalWidth >= 200, previousKey);
    await closeLogin(page);
    const pollCount = await page.evaluate(() => window.__nativeMock.requests.filter(request => request.path === '/api/login/qr/check').length);
    await page.waitForTimeout(2300);
    assert.equal(await page.evaluate(() => window.__nativeMock.requests.filter(request => request.path === '/api/login/qr/check').length), pollCount);
    record('801/802/800 states, expiry hiding, fresh-key retry and close stopping polling');

    await login(page, 'late');
    await page.waitForFunction(() => window.__nativeMock.held.length > 0);
    await closeLogin(page);
    const lateStatusCount = await page.evaluate(() => window.__nativeMock.statusCalls);
    await page.evaluate(() => window.__nativeMock.releaseHeld());
    await page.waitForTimeout(300);
    assert.equal(await page.evaluate(() => window.loginStatus.loggedIn), false);
    assert.equal(await page.evaluate(() => window.__nativeMock.statusCalls), lateStatusCount);
    assert.ok(await page.evaluate(() => window.__nativeMock.requests.some(request => request.type === 'cancel')));
    record('close cancels native in-flight RPC and a late 803 cannot log in');

    await login(page, 'unverified');
    await page.waitForFunction(() => /凭据待验证/.test(document.getElementById('qr-status').textContent));
    assert.equal(await page.evaluate(() => window.loginStatus.loggedIn), false);
    record('803 saved-but-unverified credentials remain logged out');
    await closeLogin(page);

    await login(page, 'success');
    const priorStatus = await page.evaluate(() => window.__nativeMock.statusCalls);
    await page.waitForFunction(() => window.loginStatus.loggedIn && window.loginStatus.verified, null, { timeout: 12000 });
    assert.ok(await page.evaluate(previous => window.__nativeMock.statusCalls > previous, priorStatus));
    await page.waitForFunction(() => window.userPlaylists.some(list => list.name === 'MOCK 验证后歌单'));
    record('verified mock 803 is independently rechecked and refreshes the mock account playlist');
    await closeLogin(page); await page.locator('#user-btn').click(); await page.locator('#account-logout-btn').click();
    await page.waitForFunction(() => !window.loginStatus.loggedIn);
    record('logout clears the mock account state');

    await login(page, 'pending'); await page.locator('#login-provider-qq').click();
    await page.locator('#qq-cookie-input').fill('MOCK_INVALID_COOKIE_NO_ACCOUNT_DATA'); await page.locator('#qq-cookie-save-btn').click();
    await page.waitForFunction(() => /Cookie 无效/.test(document.getElementById('qr-status').textContent));
    assert.equal(await page.evaluate(() => window.qqLoginStatus.loggedIn), false);
    await closeLogin(page); record('invalid mock QQ Cookie displays rejection without login success');

    await page.locator('#android-local-entry').click();
    await page.evaluate(() => window.dispatchEvent(new Event('android-file-picker-cancel')));
    assert.match(await page.locator('#android-local-status').innerText(), /取消/);
    assert.equal(await page.locator('#android-local-queue li').count(), 0);
    await page.locator('#android-local-files').setInputFiles([{ name: 'MOCK 本地测试音频.mp3', mimeType: 'audio/mpeg', buffer: fs.readFileSync(mp3) }]);
    await page.waitForFunction(() => window.audio.currentTime > 0.2 && !window.audio.paused);
    await page.locator('#android-local-toggle').click();
    const pauseTime = await page.evaluate(() => window.audio.currentTime);
    await page.waitForTimeout(150); assert.equal(await page.evaluate(() => window.audio.currentTime), pauseTime);
    await page.locator('#android-local-progress').fill('4'); await page.locator('#android-local-progress').dispatchEvent('input');
    assert.ok(await page.evaluate(() => window.audio.currentTime >= 4));
    await page.locator('#android-local-toggle').click();
    await page.waitForFunction(() => window.audio.currentTime > 4.1 && !window.audio.paused);
    await page.screenshot({ path: path.join(output, 'android-builtin-mock-local.png') });
    record('simulated chooser cancel preserves the queue; a real MP3 plays, pauses, seeks and resumes locally');
    bridgeRequests = await page.evaluate(() => window.__nativeMock.requests);
    await page.close();

    const racePage = await createPage(true);
    const race = await racePage.evaluate(async () => {
      const pending = window.showLoginModal({ provider: 'netease' });
      window.closeLoginModal(); window.__nativeMock.releaseConfig(); await pending;
      await new Promise(resolve => setTimeout(resolve, 100));
      return window.__nativeMock.requests.filter(request => request.path === '/api/login/qr/key').length;
    });
    assert.equal(race, 0);
    await racePage.close(); record('closing while first getConfig is pending cannot restart QR generation');
    assert.deepEqual(external, []); assert.deepEqual(pageErrors, []); assert.deepEqual(consoleErrors, []);
    assert.equal(httpRequests.some(request => request.path.startsWith('/api/')), false);
    assert.equal(bridgeRequests.some(request => request.type === 'saveConfig'), false);
    passed = true;
  } finally {
    const result = { passed, scope: 'Chromium with strict simulated MineradioNative; mock account and fake QR keys only. Not an Android or official-login test.',
      checks, pageErrors, consoleErrors, externalRequests: external, httpRequests, nativeBridgeRequests: bridgeRequests };
    fs.writeFileSync(path.join(output, 'android-builtin-mock-results.json'), JSON.stringify(result, null, 2));
    console.log(JSON.stringify({ passed, checks, pageErrors, consoleErrors, externalRequests: external.length }, null, 2));
    if (browser) await browser.close();
    await new Promise(resolve => server.close(resolve));
    fs.rmSync(temporary, { recursive: true, force: true });
  }
}
main().catch(error => { console.error(error); process.exitCode = 1; });
